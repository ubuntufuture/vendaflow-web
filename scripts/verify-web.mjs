const sources = files("venda-web").filter(
  (p) =>
    /\.(tsx?|css)$/.test(p) && !p.includes("test") && !p.includes("stories"),
);
check("Sem driver DB/API Nest na aplicação Next", () =>
  sources.every(
    (p) =>
      !/from\s+['"](?:pg|@prisma\/client|@nestjs\/)/.test(
        fs.readFileSync(p, "utf8"),
      ),
  ),
);
const assets = [];
function inspect(dir) {
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const file = path.join(dir, entry.name);
    if (entry.isDirectory()) inspect(file);
    else if (/\.(js|css|woff2)$/.test(file)) {
      const content = fs.readFileSync(file);
      assets.push({
        file: file.replaceAll("\\", "/"),
        bytes: content.length,
        gzipBytes: gzipSync(content).length,
      });
      if (
        file.endsWith(".js") &&
        /VENDA_API_INTERNAL_ORIGIN|OIDC_CLIENT_SECRET|SESSION_HASH_KEY|FLOW_ENCRYPTION_KEY|DATABASE_URL|DEMO_ONLY/.test(
          content.toString(),
        )
      )
        throw new Error(`Marcador privado/demo no browser: ${file}`);
    }
  }
}
check(
  "Assets browser sem configuração privada, credenciais de backend ou DEMO_ONLY",
  () => {
    inspect("venda-web/.next/static");
    return assets.length > 0;
  },
);
